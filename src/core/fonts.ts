/** Decoded glyph bitmaps, row-major (w*h), keyed by character. */
function decode(font: FontId, ch: string): Uint8Array | null {
  const { w, h } = FONT_SIZES[font];
  const out = new Uint8Array(w * h);
  if (font === '3x5') {
    const g = G35[ch];
    if (!g) return null;
    for (let y = 0; y < h; y++) {
      const bits = parseInt(g[y]!, 8);
      for (let x = 0; x < w; x++) out[y * w + x] = (bits >> (w - 1 - x)) & 1;
    }
    return out;
  }
  const g = G57[ch];
  if (!g) return null;
  const rows = g.split('/');
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) out[y * w + x] = rows[y]![x] === '#' ? 1 : 0;
  return out;
}

export function glyphRows(font: FontId, ch: string): string[] | null {
  const g = font === '3x5' ? G35[ch] : G57[ch];
  return g ? (font === '3x5' ? g.split('') : g.split('/')) : null;
}

export function hasGlyph(font: FontId, ch: string): boolean {
  return (font === '3x5' ? G35[ch] : G57[ch]) !== undefined;
}

/** Renders text (with \n line breaks) into a bitmap. 1px between letters and lines; `scale` repeats each pixel. */
export function renderText(text: string, font: FontId, scale = 1): BitmapText {
  const { w: gw, h: gh } = FONT_SIZES[font];
  scale = Math.min(16, Math.max(1, Math.round(scale)));
  const lines = text.split('\n');
  const cols = Math.max(1, ...lines.map((l) => l.length));
  const w = (cols * (gw + 1) - 1) * scale;
  const h = (lines.length * (gh + 1) - 1) * scale;
  const on = new Uint8Array(Math.max(0, w) * Math.max(0, h));
  lines.forEach((line, row) => {
    [...line].forEach((raw, col) => {
      const ch = raw.toUpperCase();
      const glyph = decode(font, ch) ?? decode(font, '?')!;
      for (let y = 0; y < gh; y++) {
        for (let x = 0; x < gw; x++) {
          if (!glyph[y * gw + x]) continue;
          const px = (col * (gw + 1) + x) * scale;
          const py = (row * (gh + 1) + y) * scale;
          for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) on[(py + sy) * w + px + sx] = 1;
        }
      }
    });
  });
  return { w, h, on };
}
